#!/usr/bin/env node
/**
 * Generate repository reference pages from Bakery's Sidex-defined JSON catalogs.
 * Configuration facts come from definitions; adjacent Markdown supplies explanations.
 */
import { readFile, readdir, mkdir, writeFile, unlink } from "node:fs/promises"
import { resolve, join } from "node:path"
import { parseArgs } from "node:util"
import { fileURLToPath } from "node:url"
import { format } from "prettier"

const { values, positionals } = parseArgs({
  options: {
    repository: { type: "string", default: "core" },
    output: { type: "string" },
    check: { type: "boolean", default: false },
  },
  allowPositionals: true,
})
if (!positionals.length) {
  throw new Error(
    "Usage: node scripts/generate-reference.mjs [--repository ALIAS] [--output DIRECTORY] [--check] CATALOG.json...",
  )
}
const output = resolve(
  values.output ??
    fileURLToPath(
      new URL(
        "../src/content/docs-bakery/next/reference/core",
        import.meta.url,
      ),
    ),
)
const kinds = { rule: "rules", recipe: "recipes", layer: "layers" }
const marker =
  "<!-- Generated by scripts/generate-reference.mjs. Edit the repository definition and its Markdown documentation. -->"
const pages = new Map()
const seen = new Set()

for (const filename of positionals) {
  const catalog = JSON.parse(await readFile(filename, "utf8"))
  const kind = catalog.kind
  if (!Object.hasOwn(kinds, kind) || !Array.isArray(catalog.definitions)) {
    throw new Error(`Invalid definition catalog: ${filename}`)
  }
  if (seen.has(kind)) throw new Error(`Multiple ${kind} catalogs supplied`)
  seen.add(kind)
  const prefix = values.repository === "." ? "" : values.repository + "/"
  const items = catalog.definitions
    .filter((item) =>
      prefix ? item.name.startsWith(prefix) : !item.name.includes("/"),
    )
    .map((item) => ({ ...item, slug: item.name.slice(prefix.length) }))
    .sort((left, right) => left.name.localeCompare(right.name, "en"))
  if (!items.length && catalog.definitions.length)
    throw new Error(
      `No ${kind} definitions for repository ${values.repository}`,
    )
  const slugs = new Set()
  for (const item of items) {
    if (
      !/^[A-Za-z0-9_.-]+$/.test(item.slug) ||
      [".", ".."].includes(item.slug) ||
      slugs.has(item.slug)
    ) {
      throw new Error(`Invalid or duplicate definition name: ${item.name}`)
    }
    slugs.add(item.slug)
    pages.set(
      join(kinds[kind], item.slug, "index.md"),
      await markdown(page(kind, item)),
    )
  }
  pages.set(join(kinds[kind], "index.md"), await markdown(index(kind, items)))
}

const stale = []
for (const kind of seen) {
  for await (const relative of markdownFiles(output, kinds[kind])) {
    if (
      !pages.has(relative) &&
      (await readFile(join(output, relative), "utf8")).includes(marker)
    ) {
      stale.push(relative)
    }
  }
}
const changed = []
for (const [relative, content] of pages) {
  const target = join(output, relative)
  const current = await readFile(target, "utf8").catch((error) => {
    if (error.code === "ENOENT") return undefined
    throw error
  })
  if (current === content) continue
  if (current !== undefined && !current.includes(marker)) {
    throw new Error(`Refusing to overwrite authored page: ${target}`)
  }
  changed.push(relative)
}

if (values.check && (changed.length || stale.length)) {
  throw new Error(
    `Reference pages need regeneration: ${[...changed, ...stale].join(", ")}`,
  )
}
if (!values.check) {
  for (const relative of changed) {
    const target = join(output, relative)
    await mkdir(resolve(target, ".."), { recursive: true })
    await writeFile(target, pages.get(relative))
  }
  for (const relative of stale) await unlink(join(output, relative))
}
console.log(
  `${values.check ? "Checked" : "Generated"} ${pages.size} reference pages.`,
)

function page(kind, item) {
  const definition = item.definition
  const configuration =
    kind === "layer" ? definition.variants[0].config : definition
  let body = configuration.description ? configuration.description + "\n\n" : ""
  if (kind === "layer") {
    body +=
      "## Configurations\n\nArchitecture-specific configurations replace the default configuration. The default is used when no matching architecture override exists.\n\n"
    for (const variant of definition.variants) {
      const config = variant.config
      body += `### ${variant.architecture ?? "Default"}\n\n`
      const fields = []
      if (config.url) fields.push(["Import URL", config.url])
      if (config.parent) fields.push(["Parent", code(config.parent)])
      if (config.root) fields.push(["Root layer", "Yes"])
      if (config.recipes?.length)
        fields.push(["Recipes", config.recipes.map(code).join(", ")])
      if (config.exclude?.length)
        fields.push(["Excluded recipes", config.exclude.map(code).join(", ")])
      if (fields.length) body += table(["Setting", "Value"], fields)
      const overrides = Object.entries(config.parameters ?? {}).flatMap(
        ([recipe, parameters]) =>
          Object.entries(parameters).map(([name, value]) => [
            code(recipe),
            code(name),
            code(JSON.stringify(value)),
          ]),
      )
      if (overrides.length)
        body += table(["Recipe", "Parameter", "Value"], overrides)
      if (config.rules || config.inputs) {
        body +=
          "Artifact prerequisites and input bindings:\n\n" +
          json({ rules: config.rules, inputs: config.inputs })
      }
    }
  } else {
    body += inputs(definition)
    body += parameters(definition.parameters)
    if (kind === "recipe") {
      body +=
        "## Scheduling\n\n" +
        table(
          ["Setting", "Value"],
          [
            ["Priority", code(String(definition.priority ?? 0))],
            [
              "Dependencies",
              definition.dependencies?.map(code).join(", ") || "None",
            ],
          ],
        )
      body +=
        "Higher priorities run first within the selected recipe set. Dependencies include other recipes; their priorities determine execution order.\n\n"
      if (definition.rules)
        body += "## Prerequisite Rules\n\n" + json(definition.rules)
    } else {
      const execution = definition.execution
      body += "## Outputs\n\n"
      if (execution.type === "run") {
        body += table(
          ["Name", "Kind", "Description"],
          Object.entries(execution.outputs).map(([name, port]) => [
            code(name),
            port.kind,
            port.description ?? "",
          ]),
        )
      } else if (execution.type === "graph") {
        body += table(
          ["Name", "Artifact Source"],
          Object.entries(execution.outputs).map(([name, source]) => [
            code(name),
            code(JSON.stringify(source)),
          ]),
        )
      } else {
        body +=
          "Builds layer " +
          code(execution.layer) +
          " for " +
          code(execution.architecture) +
          " and exports its layer artifacts.\n\n"
      }
      if (definition.secrets?.length) {
        body +=
          "## Secrets\n\nRequired secret bindings: " +
          definition.secrets.map(code).join(", ") +
          ". Secret changes invalidate cached outputs.\n\n"
      }
      body += "## Execution\n\n"
      if (execution.type === "run") {
        const owner = item.name.includes("/")
          ? item.name.split("/")[0] + "/"
          : ""
        const env = execution.env
          ? code(
              execution.env.includes("/")
                ? execution.env
                : owner + execution.env,
            )
          : "Bakery"
        body += table(
          ["Setting", "Value"],
          [
            ["Environment", env],
            [
              "Source epoch",
              execution["uses-source-date-epoch"] === false
                ? "Ignored"
                : "Consumed",
            ],
            [
              "Output cache",
              execution.cache === false ? "Disabled" : "Allowed",
            ],
          ],
        )
      } else {
        body +=
          execution.type === "graph"
            ? "Composes other rules into a build graph.\n\n"
            : "Uses Bakery's layer builder.\n\n"
      }
    }
  }
  if (item.documentation?.trim()) body += item.documentation.trim() + "\n"
  return (
    frontmatter(item.name, configuration.description) + marker + "\n\n" + body
  )
}

function inputs(definition) {
  const ports = Object.entries(definition.inputs ?? {})
  let result = "## Inputs\n\n"
  result += ports.length
    ? table(
        ["Name", "Kind", "Description"],
        ports.map(([name, port]) => [
          code(name),
          port.kind,
          port.description ?? "",
        ]),
      )
    : "No artifact inputs.\n\n"
  if (definition["input-defaults"]) {
    result += "Default input bindings:\n\n" + json(definition["input-defaults"])
  }
  return result
}

function parameters(definitions) {
  const entries = Object.entries(definitions ?? {})
  if (!entries.length) return ""
  return (
    "## Parameters\n\n" +
    table(
      ["Name", "Default", "Description"],
      entries.map(([name, parameter]) => [
        code(name),
        Object.hasOwn(parameter, "default")
          ? code(JSON.stringify(parameter.default))
          : "**Required**",
        parameter.description ?? "",
      ]),
    )
  )
}

function index(kind, items) {
  const title = { rule: "Rules", recipe: "Recipes", layer: "Layers" }[kind]
  const description = {
    rule: "Artifact transformations and compositions supplied by this repository.",
    recipe: "Root filesystem customizations supplied by this repository.",
    layer: "Base filesystems supplied by this repository.",
  }[kind]
  const groups = new Map()
  for (const item of items) {
    const config =
      kind === "layer" ? item.definition.variants[0].config : item.definition
    const category = config.category ?? "Definitions"
    if (!groups.has(category)) groups.set(category, [])
    groups
      .get(category)
      .push([`[${code(item.name)}](./${item.slug}/)`, config.description ?? ""])
  }
  let body = description + "\n\n"
  if (!items.length)
    body += "This repository currently has no definitions of this kind.\n\n"
  for (const [category, rows] of [...groups].sort(([left], [right]) =>
    left.localeCompare(right, "en"),
  )) {
    body += `## ${category}\n\n` + table(["Name", "Description"], rows)
  }
  return frontmatter(title, description) + marker + "\n\n" + body
}

function frontmatter(title, description) {
  return (
    "---\ntitle: " +
    JSON.stringify(title) +
    (description ? "\ndescription: " + JSON.stringify(description) : "") +
    "\n---\n\n"
  )
}
function table(headings, rows) {
  const row = (cells) =>
    "| " +
    cells
      .map((cell) => String(cell).replaceAll("|", "\\|").replaceAll("\n", " "))
      .join(" | ") +
    " |"
  return (
    [row(headings), row(headings.map(() => "---")), ...rows.map(row)].join(
      "\n",
    ) + "\n\n"
  )
}
function code(value) {
  const text = String(value)
  const fence = "`".repeat(
    Math.max(0, ...[...text.matchAll(/`+/g)].map((match) => match[0].length)) +
      1,
  )
  return (
    fence +
    (text.startsWith("`") || text.endsWith("`") ? " " + text + " " : text) +
    fence
  )
}
function json(value) {
  return "```json\n" + JSON.stringify(value, null, 2) + "\n```\n\n"
}
async function markdown(content) {
  return format(content, { parser: "markdown", proseWrap: "always" })
}

async function* markdownFiles(root, relative) {
  const entries = await readdir(join(root, relative), {
    withFileTypes: true,
  }).catch((error) => {
    if (error.code === "ENOENT") return []
    throw error
  })
  for (const entry of entries) {
    const path = join(relative, entry.name)
    if (entry.isDirectory()) yield* markdownFiles(root, path)
    else if (entry.isFile() && entry.name.endsWith(".md")) yield path
  }
}
